# End-to-End Analysis Pipeline
# ==============================================================================

def run_spatial_analysis(
    config: Optional[SpatialAnalysisConfig] = None,
    sedona_session=None,
) -> Dict[str, Any]:
    """Execute end-to-end GeoPulse Week 2 spatial analysis pipeline.

    Steps:
    1. Validate input file existence and pure Python validation checks.
    2. Initialize/use Sedona SparkSession.
    3. Ingest mobility pings and store locations CSVs.
    4. Generate and validate 500m store catchments in EPSG:32643.
    5. Project mobility pings to EPSG:32643.
    6. Execute spatial join (ST_Intersects) and distance calculation.
    7. Compute per-store metrics, overlap distribution, and reconcile totals.
    8. Write the 3 standard Spark CSV output directories safely.
    9. Return execution summary metrics.
    """
    cfg = config or SpatialAnalysisConfig()

    mobility_csv = Path(cfg.mobility_input_path).resolve()
    store_csv = Path(cfg.store_input_path).resolve()

    if not mobility_csv.is_file():
        raise FileNotFoundError(f"Mobility pings CSV not found: {mobility_csv}")
    if not store_csv.is_file():
        raise FileNotFoundError(f"Store locations CSV not found: {store_csv}")

    # Validate store reference data using pure Python validator
    with open(store_csv, "r", encoding="utf-8") as f:
        store_reader = csv.DictReader(f)
        store_records = list(store_reader)
    validate_store_records(store_records)

    # Validate mobility CSV with thorough error handling
    validate_mobility_csv(mobility_csv)

    # Create Sedona session if not passed
    close_session = False
    if sedona_session is None:
        sedona_session = create_sedona_session()
        close_session = True

    try:
        # 1. Read input CSVs via Spark (without inferSchema to preserve exact string formats)
        stores_df = (
            sedona_session.read.option("header", "true")
            .csv(str(store_csv))
        )
        mobility_df = (
            sedona_session.read.option("header", "true")
            .csv(str(mobility_csv))
        )

        total_input_pings = mobility_df.count()
        total_input_stores = stores_df.count()

        if total_input_stores != cfg.expected_store_count:
            raise ValueError(
                f"Expected {cfg.expected_store_count} stores, loaded {total_input_stores}."
            )

        # 2. Build and validate store catchments
        catchments_df = build_store_catchments(sedona_session, stores_df, cfg)
        catchments_rows = catchments_df.collect()

        if len(catchments_rows) != cfg.expected_store_count:
            raise ValueError(
                f"Catchments count mismatch: expected {cfg.expected_store_count}, got {len(catchments_rows)}."
            )

        for c_row in catchments_rows:
            if not c_row["is_valid"]:
                raise ValueError(f"Catchment geometry for store '{c_row['store_id']}' is invalid!")
            area = float(c_row["area_sq_meters"])
            if not validate_catchment_area(area, cfg.catchment_radius_meters, cfg.area_tolerance_pct):
                raise ValueError(
                    f"Catchment area {area} for store '{c_row['store_id']}' outside tolerance."
                )

        # 3. Project mobility pings
        mobility_proj_df = build_projected_mobility(sedona_session, mobility_df, cfg)

        # 4. Spatial membership join
        memberships_df = execute_spatial_membership_join(mobility_proj_df, catchments_df)
        total_memberships = memberships_df.count()

        # Distinct counts across all stores
        overall_distinct_pings = memberships_df.select("ping_id").distinct().count()
        overall_distinct_devices = memberships_df.select("device_id").distinct().count()

        # 5. Catchment summary
        summary_df = calculate_catchment_summary(memberships_df, catchments_df)
        summary_rows = summary_df.collect()

        # 6. Detailed overlap distribution & reconciliation
        overlap_metrics = calculate_catchment_overlap_metrics(memberships_df)

        # 7. Write output datasets to data/processed/ with directory protection
        # A) store_catchments: store_id, store_name, radius_meters, area_sq_meters, geometry_wkt, crs
        catchments_cols = [
            "store_id",
            "store_name",
            "radius_meters",
            "area_sq_meters",
            "geometry_wkt",
            "crs",
        ]
        write_spark_csv_output(
            catchments_df,
            cfg.catchments_output_path,
            catchments_cols,
            overwrite=cfg.overwrite,
        )

        # B) store_catchment_memberships: ping_id, device_id, event_timestamp, store_id, store_name, distance_meters, movement_mode, data_provenance
        memberships_cols = [
            "ping_id",
            "device_id",
            "event_timestamp",
            "store_id",
            "store_name",
            "distance_meters",
            "movement_mode",
            "data_provenance",
        ]
        write_spark_csv_output(
            memberships_df,
            cfg.memberships_output_path,
            memberships_cols,
            overwrite=cfg.overwrite,
        )

        # C) store_catchment_summary: store_id, store_name, matched_pings, distinct_devices, multi_catchment_pings
        summary_cols = [
            "store_id",
            "store_name",
            "matched_pings",
            "distinct_devices",
            "multi_catchment_pings",
        ]
        write_spark_csv_output(
            summary_df,
            cfg.summary_output_path,
            summary_cols,
            overwrite=cfg.overwrite,
        )

        # Build results payload
        per_store_metrics = [
            {
                "store_id": r["store_id"],
                "store_name": r["store_name"],
                "matched_pings": int(r["matched_pings"]),
                "distinct_devices": int(r["distinct_devices"]),
                "multi_catchment_pings": int(r["multi_catchment_pings"]),
            }
            for r in summary_rows
        ]

        results = {
            "status": "SUCCESS",
            "input_pings_count": total_input_pings,
            "input_stores_count": total_input_stores,
            "catchment_radius_meters": cfg.catchment_radius_meters,
            "source_crs": cfg.source_crs,
            "metric_crs": cfg.metric_crs,
            "total_memberships": total_memberships,
            "overall_distinct_matched_pings": overall_distinct_pings,
            "overall_distinct_matched_devices": overall_distinct_devices,
            "overlap_distribution": overlap_metrics,
            "per_store_summary": per_store_metrics,
            "outputs": {
                "catchments": str(Path(cfg.catchments_output_path).resolve()),
                "memberships": str(Path(cfg.memberships_output_path).resolve()),
                "summary": str(Path(cfg.summary_output_path).resolve()),
            },
        }

        return results

    finally:
        if close_session:
            sedona_session.stop()



def validate_catchment_radius(radius_meters: float) -> None:
    """Validate that the catchment radius is a positive, finite number."""
    if not isinstance(radius_meters, (int, float)) or isinstance(radius_meters, bool):
        raise TypeError(f"Catchment radius must be numeric, got {type(radius_meters).__name__}.")
    if not math.isfinite(radius_meters):
        raise ValueError(f"Catchment radius must be a finite number, got {radius_meters}.")
    if radius_meters <= 0:
        raise ValueError(f"Catchment radius must be strictly positive, got {radius_meters}.")



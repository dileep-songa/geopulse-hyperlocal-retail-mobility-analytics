def build_store_catchments(sedona_session, stores_df, config: SpatialAnalysisConfig):
    """Construct 500-metre metric buffer catchments around candidate stores.

    Processing:
    1. Construct geodetic points: ST_Point(longitude, latitude).
    2. Set SRID to EPSG:4326.
    3. Transform to UTM Zone 43N (EPSG:32643) for planar metric operations.
    4. Apply planar buffer: ST_Buffer(store_geom_proj, radius_meters).
    5. Compute geometry validity (ST_IsValid) and area in sq metres (ST_Area).
    6. Generate WKT representation (ST_AsText).

    Returns:
        DataFrame containing store metadata, buffer polygon geometry, WKT, and area.
    """
    stores_df.createOrReplaceTempView("raw_stores")

    catchments_sql = f"""
    SELECT
        store_id,
        store_name,
        CAST({config.catchment_radius_meters} AS Double) AS radius_meters,
        ROUND(ST_Area(catchment_geom), 2) AS area_sq_meters,
        ST_IsValid(catchment_geom) AS is_valid,
        ST_AsText(catchment_geom) AS geometry_wkt,
        '{config.metric_crs}' AS crs,
        catchment_geom,
        store_geom_proj
    FROM (
        SELECT
            store_id,
            store_name,
            store_geom_proj,
            ST_Buffer(store_geom_proj, CAST({config.catchment_radius_meters} AS Double)) AS catchment_geom
        FROM (
            SELECT
                store_id,
                store_name,
                ST_Transform(
                    ST_SetSRID(ST_Point(CAST(longitude AS Double), CAST(latitude AS Double)), 4326),
                    '{config.source_crs}',
                    '{config.metric_crs}'
                ) AS store_geom_proj
            FROM raw_stores
        )
    )
    """
    return sedona_session.sql(catchments_sql)


def build_projected_mobility(sedona_session, mobility_df, config: SpatialAnalysisConfig):
    """Project raw geodetic mobility pings into planar metric CRS (EPSG:32643).

    Processing:
    1. Construct geodetic points: ST_Point(longitude, latitude).
    2. Set SRID to EPSG:4326.
    3. Transform to UTM Zone 43N (EPSG:32643).

    Returns:
        DataFrame with original fields plus projected planar geometry `ping_geom_proj`.
    """
    mobility_df.createOrReplaceTempView("raw_mobility")

    mobility_proj_sql = f"""
    SELECT
        ping_id,
        device_id,
        event_timestamp,
        latitude,
        longitude,
        accuracy_meters,
        movement_mode,
        data_provenance,
        ST_Transform(
            ST_SetSRID(ST_Point(CAST(longitude AS Double), CAST(latitude AS Double)), 4326),
            '{config.source_crs}',
            '{config.metric_crs}'
        ) AS ping_geom_proj
    FROM raw_mobility
    """
    return sedona_session.sql(mobility_proj_sql)


def execute_spatial_membership_join(mobility_proj_df, catchments_df):
    """Execute spatial point-in-polygon join between mobility pings and store catchments.

    Condition:
    ST_Intersects(ping_geom_proj, catchment_geom)
    (Points lying on the catchment boundary count as inside).

    Distance:
    ST_Distance(ping_geom_proj, store_geom_proj) in metres rounded to 2 decimal places.

    Returns:
        DataFrame of matched catchment memberships with distance to candidate store.
    """
    mobility_proj_df.createOrReplaceTempView("mobility_proj")
    catchments_df.createOrReplaceTempView("catchments")

    membership_sql = """
    SELECT
        m.ping_id,
        m.device_id,
        m.event_timestamp,
        c.store_id,
        c.store_name,
        ROUND(ST_Distance(m.ping_geom_proj, c.store_geom_proj), 2) AS distance_meters,
        m.movement_mode,
        m.data_provenance
    FROM mobility_proj m
    INNER JOIN catchments c
        ON ST_Intersects(m.ping_geom_proj, c.catchment_geom)
    """
    return mobility_proj_df.sparkSession.sql(membership_sql)


def calculate_catchment_summary(memberships_df, catchments_df):
    """Calculate per-store summary metrics including multi-catchment overlap counts.

    Metrics per store:
    - matched_pings: Total observation pings falling within the store's 500m catchment.
    - distinct_devices: Distinct synthetic device IDs observed within the store's catchment.
    - multi_catchment_pings: Observation pings within this store's catchment that also intersect
      at least one other candidate store's catchment.

    Returns:
        DataFrame sorted by store_id.
    """
    memberships_df.createOrReplaceTempView("memberships")
    catchments_df.createOrReplaceTempView("catchments_ref")

    # Find pings that fell into >= 2 distinct store catchments
    multi_pings_sql = """
    SELECT ping_id
    FROM memberships
    GROUP BY ping_id
    HAVING COUNT(DISTINCT store_id) > 1
    """
    multi_pings_df = memberships_df.sparkSession.sql(multi_pings_sql)
    multi_pings_df.createOrReplaceTempView("multi_pings")

    summary_sql = """
    SELECT
        c.store_id,
        c.store_name,
        COUNT(m.ping_id) AS matched_pings,
        COUNT(DISTINCT m.device_id) AS distinct_devices,
        COUNT(mp.ping_id) AS multi_catchment_pings
    FROM catchments_ref c
    LEFT JOIN memberships m
        ON c.store_id = m.store_id
    LEFT JOIN multi_pings mp
        ON m.ping_id = mp.ping_id
    GROUP BY c.store_id, c.store_name
    ORDER BY c.store_id
    """
    return memberships_df.sparkSession.sql(summary_sql)


def calculate_catchment_overlap_metrics(memberships_df) -> Dict[str, Any]:
    """Calculate disjoint overlap distribution categories and assert full reconciliation.

    Groups memberships by ping_id and counts how many distinct catchments each ping intersects.
    Calculates:
    - pings_exactly_one_catchment
    - pings_exactly_two_catchments
    - pings_three_or_more_catchments
    - pings_multiple_catchments
    - total_unique_matched_pings
    - reconciled: boolean asserting exact reconciliation
    """
    memberships_df.createOrReplaceTempView("memberships_overlap")

    ping_counts_sql = """
    SELECT
        ping_id,
        COUNT(DISTINCT store_id) AS store_count
    FROM memberships_overlap
    GROUP BY ping_id
    """
    ping_counts_df = memberships_df.sparkSession.sql(ping_counts_sql)
    ping_counts_df.createOrReplaceTempView("ping_counts")

    distribution_sql = """
    SELECT
        COUNT(CASE WHEN store_count = 1 THEN 1 END) AS pings_exactly_one,
        COUNT(CASE WHEN store_count = 2 THEN 1 END) AS pings_exactly_two,
        COUNT(CASE WHEN store_count >= 3 THEN 1 END) AS pings_three_or_more,
        COUNT(CASE WHEN store_count > 1 THEN 1 END) AS pings_multiple,
        COUNT(*) AS total_unique_matched_pings
    FROM ping_counts
    """
    dist_row = memberships_df.sparkSession.sql(distribution_sql).collect()[0]

    count_1 = int(dist_row["pings_exactly_one"] or 0)
    count_2 = int(dist_row["pings_exactly_two"] or 0)
    count_3_plus = int(dist_row["pings_three_or_more"] or 0)
    count_multi = int(dist_row["pings_multiple"] or 0)
    total_unique = int(dist_row["total_unique_matched_pings"] or 0)

    # Reconciliation assertion
    is_reconciled = (
        (count_1 + count_multi == total_unique)
        and (count_2 + count_3_plus == count_multi)
        and (count_1 + count_2 + count_3_plus == total_unique)
    )
    if not is_reconciled:
        raise ValueError(
            f"Spark overlap reconciliation failed: count_1={count_1}, count_2={count_2}, "
            f"count_3_plus={count_3_plus}, multi={count_multi}, total={total_unique}"
        )

    return {
        "pings_exactly_one_catchment": count_1,
        "pings_exactly_two_catchments": count_2,
        "pings_three_or_more_catchments": count_3_plus,
        "pings_multiple_catchments": count_multi,
        "total_unique_matched_pings": total_unique,
        "reconciled": is_reconciled,
    }


# ==============================================================================
# Safe Native Spark CSV Output Writer
# ==============================================================================

def write_spark_csv_output(
    df,
    output_dir: str | Path,
    selected_columns: Optional[List[str]] = None,
    overwrite: bool = False,
) -> Path:
    """Write DataFrame to standard Spark CSV directory structure with headers.

    Enforces safety guarantees:
    - Never deletes or replaces existing output directories automatically.
    - If output_dir exists and overwrite is False, raises FileExistsError immediately.
    - Uses Spark's native CSV writer with mode('errorifexists') by default.
    - Only if overwrite is explicitly True, allows Spark write with mode('overwrite').

    Args:
        df: PySpark DataFrame to persist.
        output_dir: Target output directory path.
        selected_columns: Optional column subset to project.
        overwrite: Explicit permission to overwrite existing output. Default is False.

    Returns:
        Resolved Path to the written output directory.
    """
    out_path = Path(output_dir).resolve()

    if out_path.exists() and not overwrite:
        raise FileExistsError(
            f"Output directory already exists: '{out_path}'. "
            "To prevent accidental data loss, existing outputs are not replaced automatically. "
            "Specify overwrite=True to allow replacement."
        )

    if selected_columns:
        df = df.select(*selected_columns)

    write_mode = "overwrite" if overwrite else "errorifexists"

    # Use Spark's native CSV writer as required
    df.write.mode(write_mode).option("header", "true").csv(str(out_path))

    logger.info("Successfully wrote Spark CSV output: %s", out_path)
    return out_path



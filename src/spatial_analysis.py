def calculate_theoretical_circle_area(radius_meters: float) -> float:
    """Calculate the theoretical planar area of a circle in square metres (pi * r^2)."""
    validate_catchment_radius(radius_meters)
    return math.pi * (radius_meters ** 2)


def calculate_polygon_buffer_area(radius_meters: float, segments_per_quadrant: int = 8) -> float:
    """Calculate the area of a regular polygon approximation generated by ST_Buffer.

    ST_Buffer approximates circles as regular polygons with 4 * segments_per_quadrant vertices
    (32 vertices by default in JTS/GEOS/Sedona).
    """
    validate_catchment_radius(radius_meters)
    if not isinstance(segments_per_quadrant, int) or isinstance(segments_per_quadrant, bool):
        raise TypeError(
            f"segments_per_quadrant must be an integer, got {type(segments_per_quadrant).__name__}."
        )
    if segments_per_quadrant < 1:
        raise ValueError(
            f"segments_per_quadrant must be an integer >= 1, got {segments_per_quadrant}."
        )
    num_vertices = 4 * segments_per_quadrant
    angle = 2.0 * math.pi / num_vertices
    return 0.5 * num_vertices * (radius_meters ** 2) * math.sin(angle)


def validate_catchment_area(
    actual_area: float,
    radius_meters: float,
    tolerance_pct: float = 0.02,
) -> bool:
    """Validate that a measured buffer polygon area matches the expected geometric area."""
    if actual_area <= 0:
        return False
    try:
        validate_catchment_radius(radius_meters)
    except (ValueError, TypeError):
        return False

    expected_polygon_area = calculate_polygon_buffer_area(radius_meters)
    lower = expected_polygon_area * (1.0 - tolerance_pct)
    upper = expected_polygon_area * (1.0 + tolerance_pct)
    return lower <= actual_area <= upper


def validate_store_records(records: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Validate store location records before spatial processing.

    Validates:
    - Non-empty records list.
    - Expected store count (4).
    - Required columns existence.
    - Valid coordinates within study area bounds (finite and geographically valid).
    - Non-empty unique store IDs.
    - Required metadata: location_type is 'hypothetical_candidate' and data_provenance is 'geopulse_synthetic_v1'.

    Returns:
        Dictionary summarizing validation status and parsed store data.
    """
    if not records:
        raise ValueError("Store location records must not be empty.")

    if len(records) != EXPECTED_STORE_COUNT:
        raise ValueError(
            f"Expected exactly {EXPECTED_STORE_COUNT} candidate store locations, got {len(records)}."
        )

    seen_store_ids = set()
    validated_stores = []

    for idx, row in enumerate(records):
        for col in STORE_CSV_COLUMNS:
            if col not in row or str(row[col]).strip() == "":
                raise ValueError(f"Store record {idx} missing required field '{col}'.")

        store_id = str(row["store_id"]).strip()
        if store_id in seen_store_ids:
            raise ValueError(f"Duplicate store_id detected: '{store_id}'.")
        seen_store_ids.add(store_id)

        # Validate location_type
        loc_type = str(row["location_type"]).strip()
        if loc_type not in VALID_STORE_LOCATION_TYPES:
            raise ValueError(
                f"Store '{store_id}' has invalid location_type '{loc_type}'. "
                f"Expected one of {sorted(VALID_STORE_LOCATION_TYPES)}."
            )

        # Validate data_provenance
        prov = str(row["data_provenance"]).strip()
        if prov != DATA_PROVENANCE_TAG:
            raise ValueError(
                f"Store '{store_id}' has invalid data_provenance '{prov}'. "
                f"Expected '{DATA_PROVENANCE_TAG}'."
            )

        try:
            lon = float(row["longitude"])
            lat = float(row["latitude"])
        except (ValueError, TypeError) as exc:
            raise ValueError(f"Invalid coordinate format for store '{store_id}': {exc}") from exc

        if not math.isfinite(lon) or not math.isfinite(lat):
            raise ValueError(f"Store '{store_id}' coordinates ({lon}, {lat}) must be finite numbers.")

        coord_err = validate_coordinate(lon, lat)
        if coord_err:
            raise ValueError(f"Store '{store_id}' coordinate invalid: {coord_err}")

        if not STUDY_AREA.bounds.contains(lon, lat):
            raise ValueError(
                f"Store '{store_id}' coordinates ({lon}, {lat}) fall outside "
                f"study area bounding box {STUDY_AREA.bounds}."
            )

        validated_stores.append({
            "store_id": store_id,
            "store_name": str(row["store_name"]).strip(),
            "longitude": lon,
            "latitude": lat,
            "location_type": loc_type,
            "data_provenance": prov,
        })

    return {
        "valid": True,
        "count": len(validated_stores),
        "stores": validated_stores,
    }


def validate_mobility_schema(columns: List[str]) -> bool:
    """Validate that mobility ping columns conform to the canonical 8-field schema."""
    if not columns:
        return False
    return list(columns) == MOBILITY_CSV_COLUMNS


def validate_mobility_record(
    row: Dict[str, Any],
    bounds=STUDY_AREA.bounds,
    seen_ping_ids: Optional[Set[str]] = None,
) -> None:
    """Validate a single mobility ping observation record.

    Validates:
    - ping_id: non-empty string, unique if seen_ping_ids set is provided.
    - device_id: non-empty string.
    - event_timestamp: non-empty string.
    - coordinates (latitude, longitude): numeric, finite, geographically valid, and inside bounds.
    - accuracy_meters: numeric, finite, positive.
    - movement_mode: allowed MovementMode enum value.
    - data_provenance: matches DATA_PROVENANCE_TAG.
    """
    if "ping_id" not in row or not str(row["ping_id"]).strip():
        raise ValueError("Missing or blank 'ping_id' in mobility record.")
    ping_id = str(row["ping_id"]).strip()

    if seen_ping_ids is not None:
        if ping_id in seen_ping_ids:
            raise ValueError(f"Duplicate ping_id detected: '{ping_id}'.")
        seen_ping_ids.add(ping_id)

    if "device_id" not in row or not str(row["device_id"]).strip():
        raise ValueError(f"Record '{ping_id}' missing or blank 'device_id'.")

    if "event_timestamp" not in row or not str(row["event_timestamp"]).strip():
        raise ValueError(f"Record '{ping_id}' missing or blank 'event_timestamp'.")

    # Coordinates
    for coord_col in ("longitude", "latitude"):
        if coord_col not in row or str(row[coord_col]).strip() == "":
            raise ValueError(f"Record '{ping_id}' missing required coordinate '{coord_col}'.")

    try:
        lon = float(row["longitude"])
        lat = float(row["latitude"])
    except (ValueError, TypeError) as exc:
        raise ValueError(f"Record '{ping_id}' has non-numeric coordinates: {exc}") from exc

    if not math.isfinite(lon):
        raise ValueError(f"Record '{ping_id}' longitude {lon} is not a finite number.")
    if not math.isfinite(lat):
        raise ValueError(f"Record '{ping_id}' latitude {lat} is not a finite number.")

    coord_err = validate_coordinate(lon, lat)
    if coord_err:
        raise ValueError(f"Record '{ping_id}' coordinate invalid: {coord_err}")

    if not bounds.contains(lon, lat):
        raise ValueError(
            f"Record '{ping_id}' coordinates ({lon}, {lat}) fall outside "
            f"study area bounding box {bounds}."
        )

    # Accuracy
    if "accuracy_meters" not in row or str(row["accuracy_meters"]).strip() == "":
        raise ValueError(f"Record '{ping_id}' missing 'accuracy_meters'.")
    try:
        acc = float(row["accuracy_meters"])
    except (ValueError, TypeError) as exc:
        raise ValueError(f"Record '{ping_id}' has non-numeric accuracy_meters: {exc}") from exc
    if not math.isfinite(acc) or acc <= 0:
        raise ValueError(f"Record '{ping_id}' has non-positive/non-finite accuracy: {acc}.")

    # Movement Mode
    if "movement_mode" not in row or not str(row["movement_mode"]).strip():
        raise ValueError(f"Record '{ping_id}' missing or blank 'movement_mode'.")
    allowed_modes = {mode.value for mode in MovementMode}
    mode = str(row["movement_mode"]).strip()
    if mode not in allowed_modes:
        raise ValueError(
            f"Record '{ping_id}' movement_mode '{mode}' not in allowed modes: {sorted(allowed_modes)}."
        )

    # Data Provenance
    if "data_provenance" not in row or not str(row["data_provenance"]).strip():
        raise ValueError(f"Record '{ping_id}' missing 'data_provenance'.")
    prov = str(row["data_provenance"]).strip()
    if prov != DATA_PROVENANCE_TAG:
        raise ValueError(
            f"Record '{ping_id}' data_provenance '{prov}' does not match expected '{DATA_PROVENANCE_TAG}'."
        )


def validate_mobility_csv(
    file_path: str | Path,
    bounds=STUDY_AREA.bounds,
    max_records: Optional[int] = None,
) -> Dict[str, Any]:
    """Validate synthetic mobility CSV file headers, structure, and record contents.

    Handles empty CSV files without raising an unhandled StopIteration.
    Validates canonical 8 columns.
    Validates records for coordinate ranges, identifier uniqueness, movement mode, and provenance.
    """
    path = Path(file_path).resolve()
    if not path.is_file():
        raise FileNotFoundError(f"Mobility CSV file not found: {path}")

    with open(path, "r", encoding="utf-8") as f:
        reader = csv.reader(f)
        try:
            headers = next(reader)
        except StopIteration:
            raise ValueError(f"Mobility CSV file is completely empty: {path}")

    if not validate_mobility_schema(headers):
        raise ValueError(
            f"Mobility CSV columns {headers} do not match canonical schema {MOBILITY_CSV_COLUMNS}."
        )

    seen_ping_ids: Set[str] = set()
    record_count = 0

    with open(path, "r", encoding="utf-8") as f:
        dict_reader = csv.DictReader(f)
        for row in dict_reader:
            validate_mobility_record(row, bounds=bounds, seen_ping_ids=seen_ping_ids)
            record_count += 1
            if max_records and record_count >= max_records:
                break

    if record_count == 0:
        raise ValueError(f"Mobility CSV file contains headers but zero data records: {path}")

    return {
        "valid": True,
        "record_count": record_count,
        "unique_pings": len(seen_ping_ids),
    }


def calculate_overlap_distribution(
    memberships: List[Dict[str, Any]],
) -> Dict[str, Any]:
    """Group memberships by ping ID and compute catchment intersection distribution.

    Counts:
    - pings_exactly_one_catchment: Pings intersecting exactly 1 catchment.
    - pings_exactly_two_catchments: Pings intersecting exactly 2 catchments.
    - pings_three_or_more_catchments: Pings intersecting >= 3 catchments.
    - pings_multiple_catchments: Total unique pings intersecting >= 2 catchments.
    - total_unique_matched_pings: Total distinct matched ping IDs.

    Reconciles:
    - (pings_exactly_one + pings_multiple) == total_unique_matched_pings
    - (pings_exactly_two + pings_three_or_more) == pings_multiple_catchments
    """
    ping_to_stores: Dict[str, Set[str]] = {}
    for m in memberships:
        p_id = str(m["ping_id"]).strip()
        s_id = str(m["store_id"]).strip()
        if p_id not in ping_to_stores:
            ping_to_stores[p_id] = set()
        ping_to_stores[p_id].add(s_id)

    total_unique = len(ping_to_stores)
    count_1 = 0
    count_2 = 0
    count_3_plus = 0

    for stores in ping_to_stores.values():
        k = len(stores)
        if k == 1:
            count_1 += 1
        elif k == 2:
            count_2 += 1
        elif k >= 3:
            count_3_plus += 1

    count_multi = count_2 + count_3_plus

    # Reconciliation check
    is_reconciled = (
        (count_1 + count_multi == total_unique)
        and (count_2 + count_3_plus == count_multi)
    )
    if not is_reconciled:
        raise ValueError(
            f"Overlap reconciliation failed: count_1={count_1}, count_2={count_2}, "
            f"count_3_plus={count_3_plus}, multi={count_multi}, total={total_unique}"
        )

    return {
        "pings_exactly_one_catchment": count_1,
        "pings_exactly_two_catchments": count_2,
        "pings_three_or_more_catchments": count_3_plus,
        "pings_multiple_catchments": count_multi,
        "total_unique_matched_pings": total_unique,
        "reconciled": is_reconciled,
    }


